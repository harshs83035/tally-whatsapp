-- Tally-to-WhatsApp Document Automation: schema (as per PRD)

-- 1. Customers (synced from Tally Sundry Debtors)
CREATE TABLE customers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tally_ledger_guid VARCHAR(255) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    billing_address TEXT,
    shipping_address TEXT,
    gstin VARCHAR(15),
    phone VARCHAR(20), -- Critical for WhatsApp routing
    email VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Products (synced from Tally Stock Items)
CREATE TABLE products (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tally_item_guid VARCHAR(255) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    hsn_sac_code VARCHAR(20),
    uom VARCHAR(20), -- Unit of Measure (e.g., KGS, NOS)
    base_price DECIMAL(12, 2) DEFAULT 0.00,
    tax_rate DECIMAL(5, 2) DEFAULT 0.00, -- e.g., 18.00 for 18% GST
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Documents (generated by the app)
CREATE TYPE document_type_enum AS ENUM ('QUOTATION', 'INVOICE', 'DELIVERY_CHALLAN');
CREATE TYPE whatsapp_status_enum AS ENUM ('PENDING', 'SENT', 'FAILED');

CREATE TABLE documents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES customers(id) ON DELETE RESTRICT,
    type document_type_enum NOT NULL,
    document_number VARCHAR(50) UNIQUE NOT NULL,
    document_date DATE NOT NULL,
    due_date DATE,

    -- Financial totals
    sub_total DECIMAL(15, 2) NOT NULL DEFAULT 0.00,
    tax_total DECIMAL(15, 2) NOT NULL DEFAULT 0.00,
    grand_total DECIMAL(15, 2) NOT NULL DEFAULT 0.00,

    -- Attachments & tracking
    pdf_url TEXT, -- Link to the PDF in Supabase Storage
    whatsapp_status whatsapp_status_enum DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Document line items
CREATE TABLE document_line_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    document_id UUID REFERENCES documents(id) ON DELETE CASCADE,
    product_id UUID REFERENCES products(id) ON DELETE RESTRICT,

    -- Snapshot of pricing at the time of document creation
    quantity DECIMAL(10, 2) NOT NULL,
    unit_price DECIMAL(15, 2) NOT NULL,
    discount_amount DECIMAL(15, 2) DEFAULT 0.00,
    tax_amount DECIMAL(15, 2) NOT NULL DEFAULT 0.00,
    line_total DECIMAL(15, 2) NOT NULL, -- (Quantity * Unit Price) - Discount + Tax

    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Storage bucket for generated PDFs
INSERT INTO storage.buckets (id, name, public)
VALUES ('documents', 'documents', true)
ON CONFLICT (id) DO NOTHING;
